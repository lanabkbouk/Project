// إعداد QueryClient بمكان واحد (بدل تكراره أو نشره بأكثر من مكان)، عشان
// أي صفحة تحتاج تضبط سلوك caching استثنائي تقدر تستورد نفس النسخة.
import { QueryClient } from '@tanstack/react-query'

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // البيانات تضل "طازجة" لدقيقة كاملة قبل ما React Query يعتبرها
      // قديمة ويعيد جلبها تلقائيًا — مناسب لبيانات زي الفرص/التصنيفات
      // اللي ما بتتغيّر كل ثانية، ويقلل عدد الطلبات غير الضرورية.
      staleTime: 60 * 1000,

      // إعادة المحاولة مرة وحدة بس عند الفشل (بدل 3 محاولات الافتراضية)
      // — الفشل الأكثر شيوعًا هون هو خطأ حقيقي (401/422)، مو انقطاع شبكة
      // مؤقت، فمحاولات إضافية بترجع نفس الخطأ وبس بتأخّر ظهور الرسالة
      retry: 1,

      // ما نعيد الجلب تلقائيًا كل مرة المستخدم يرجع لتبويب المتصفح —
      // سلوك أكثر هدوءًا للمستخدم، وبيقدر يعمل refresh يدوي لو احتاج
      refetchOnWindowFocus: false,
    },
  },
})